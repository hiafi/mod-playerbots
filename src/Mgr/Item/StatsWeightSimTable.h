// Rework: gear stat weights measured with mod-dpssim, one row per spec, level 60. Round 4 (2026-11-22): every row
// re-simmed on the level-60 stat-curve server (secondary curve, Cooldown Haste 14 and Block 7 rating per 1%, potency
// rebase) with big steps (about +25 percentage points per rating; 3 x 5 baseline runs, 5 runs per stat, one refinement
// batch for a noisy or negative weight). GENERATED by gen_cpp.py from final_weights.json in the private docs repo
// (docs/plans/bot-stat-weights/, with the R4-REPORT: sims, report paths, method). StatsWeightCalculator::
// ApplySimWeights() writes a row's stats over the class block's values; a stat not in the row (weapon DPS, mana
// regeneration, the off-role penalties, the defensive ratings of a non-tank) keeps the class block's value.
//
// Values (user rulings 2026-11-11): a weight clear of its noise (|weight| > 2 SE) is the measured value. A noisy one
// is min(old class-block value, measured + 2 SE), floored at 0; a negative old value (an off-role penalty) is kept.
// The four custom stats (Mastery, Versatility, Cooldown Haste, Proc Chance) are the measured value floored at 0,
// noisy or not.
//
// Scale: each row is anchored on one stat that keeps its old class-block value: Strength 2.5 (Warriors, Ret, DKs),
// the spec's old Agility (hunters, rogues, Cat, Bestial Fury, Enhancement and the Combat / Enhancement tanks), Spell
// Power 1.0 or 1.2 (casters, healing power for healers), Intellect 2.0 (Shockadin), Stamina 3.0 / 4.0 (Prot, Blood,
// bear tank); the next stat in the spec's list when that one is inside its noise. The unmeasured stats keep their old
// ratio to it. A caster whose Intellect check (1 Intellect = 0.5 Spell Power + its crit share, ratio 0.75-1.75) fails
// keeps the class block's Intellect, Spell Power and Spirit and is anchored on its old Haste or Crit. A tank row is
// 0.7 x its defensive weight (seconds of effective health per point; Dodge, Parry, Block, Defense and Armor computed
// from the sim's own swings) + 0.3 x its damage weight (Enhancement tank: Intellect = 1). A healer row is half
// whole-fight HPS (mana limited) and half HPS before going out of mana. Hit and Expertise are 0 for every non-PvP spec.
//
// Known gaps:
// - Level 60 only: a rating converts to more percent per point at low level, a primary stat does not.
// - Cooldown Haste: measured in 120 s fights only, provisional (an average over 60/120/180/300 s is planned).
// - Resto Shaman Spirit is 0 by user ruling. Shaman rows are measured without Bloodlust and Blood Fury.
// - Mage, Warlock and Shaman Spirit is capped at 0.8 x the spec's Intellect weight (user ruling 2026-11-22).
// - To be replaced by a follow-up round: every Cooldown Haste and Proc Chance weight (their level-60 conversion moves
//   to 6 and 4 rating per 1%) and the three Warlock rows (Fel Armor loses its spell power for a 1% leech).
